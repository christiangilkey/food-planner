// Builds the Android app's launcher icon and splash screen from public/icon.svg (the VENA logo),
// as vector drawables: sharp at every size, no image tools needed. Run after changing the icon:
// `node scripts/android-icons.mjs`. The logo is scaled into Android's adaptive-icon safe zone.
import { mkdirSync, readFileSync, rmSync, writeFileSync, existsSync, readdirSync } from 'node:fs'
import { dirname, join } from 'node:path'
import { fileURLToPath } from 'node:url'

const root = join(dirname(fileURLToPath(import.meta.url)), '..')
const res = join(root, 'android', 'app', 'src', 'main', 'res')
const svg = readFileSync(join(root, 'public', 'icon.svg'), 'utf8')

const background = svg.match(/<rect[^>]*fill="(#[0-9a-fA-F]{6})"/)[1]
const strokeGroup = svg.indexOf('<g ')
// Paths and circles, filled or stroked (a stroke set on the shape itself, or inherited from a <g>).
const paths = [...svg.matchAll(/<(path|circle)\s+([^>]*?)\/>/g)].map((m) => {
  const attr = (name) => m[2].match(new RegExp(`(?:^|\\s)${name}="([^"]+)"`))?.[1]
  let d
  if (m[1] === 'circle') {
    const [cx, cy, r] = ['cx', 'cy', 'r'].map((k) => Number(attr(k)))
    d = `M${cx - r} ${cy}A${r} ${r} 0 1 0 ${cx + r} ${cy}A${r} ${r} 0 1 0 ${cx - r} ${cy}Z`
  } else d = attr('d').replace(/\s+/g, ' ').trim()
  const ownStroke = attr('stroke') && attr('fill') === 'none'
  return { d, fill: attr('fill'), stroke: attr('stroke'), strokeWidth: attr('stroke-width'), stroked: !!ownStroke || (strokeGroup >= 0 && m.index > strokeGroup) }
})

// The icon is drawn for Android: the whole mark sits inside the middle 61% circle that every
// launcher shape shows (about 610 of 1000 units from the centre), so it is placed 1:1.
const cx = 1000, cy = 1000, scale = 1
const group = (inner) => `    <group android:pivotX="1000" android:pivotY="1000" android:scaleX="${scale.toFixed(4)}" android:scaleY="${scale.toFixed(4)}" android:translateX="${(-(cx - 1000) * scale).toFixed(1)}" android:translateY="${(-(cy - 1000) * scale).toFixed(1)}">\n${inner}\n    </group>`

/** "#fff" → "#FFFFFF". */
const hex = (c) => (c && /^#[0-9a-f]{3}$/i.test(c) ? `#${[...c.slice(1)].map((x) => x + x).join('')}` : c ?? '#FFFFFF').toUpperCase()
// Dark tints barely show on the dark tile; the themed (monochrome) icon leaves them out.
const faint = (c) => { const h = hex(c); return parseInt(h.slice(1, 3), 16) + parseInt(h.slice(3, 5), 16) + parseInt(h.slice(5, 7), 16) < 120 }
const pathXml = (p, mono) => {
  if (p.stroked) return `        <path android:pathData="${p.d}" android:fillColor="#00000000" android:strokeColor="${mono ? '#FFFFFF' : hex(p.stroke)}" android:strokeWidth="${p.strokeWidth}" android:strokeLineCap="round" android:strokeLineJoin="round" />`
  if (mono && faint(p.fill)) return null
  return `        <path android:pathData="${p.d}" android:fillColor="${mono ? '#FFFFFF' : hex(p.fill)}" />`
}
const vector = (mono) => `<?xml version="1.0" encoding="utf-8"?>
<!-- Generated by scripts/android-icons.mjs from public/icon.svg. -->
<vector xmlns:android="http://schemas.android.com/apk/res/android"
    android:width="108dp" android:height="108dp"
    android:viewportWidth="2000" android:viewportHeight="2000">
${group(paths.map((p) => pathXml(p, mono)).filter(Boolean).join('\n'))}
</vector>
`

const write = (rel, text) => { const p = join(res, rel); mkdirSync(dirname(p), { recursive: true }); writeFileSync(p, text) }

// Remove the template's raster icons and Capacitor splash pictures.
for (const dir of readdirSync(res)) {
  if (/^mipmap-(m|h|xh|xxh|xxxh)dpi$/.test(dir) || /^drawable-(land|port)-/.test(dir)) rmSync(join(res, dir), { recursive: true, force: true })
}
for (const f of ['drawable/splash.png', 'drawable/ic_launcher_background.xml', 'drawable-v24/ic_launcher_foreground.xml']) if (existsSync(join(res, f))) rmSync(join(res, f))

write('drawable/ic_launcher_foreground.xml', vector(false))
write('drawable/ic_launcher_monochrome.xml', vector(true))
write('values/ic_launcher_background.xml', `<?xml version="1.0" encoding="utf-8"?>\n<resources>\n    <color name="ic_launcher_background">${background}</color>\n</resources>\n`)
const adaptive = `<?xml version="1.0" encoding="utf-8"?>
<adaptive-icon xmlns:android="http://schemas.android.com/apk/res/android">
    <background android:drawable="@color/ic_launcher_background" />
    <foreground android:drawable="@drawable/ic_launcher_foreground" />
    <monochrome android:drawable="@drawable/ic_launcher_monochrome" />
</adaptive-icon>
`
write('mipmap-anydpi-v26/ic_launcher.xml', adaptive)
write('mipmap-anydpi-v26/ic_launcher_round.xml', adaptive)
// Before Android 12 the launch screen is this drawable; from 12 Android shows the icon on the same colour.
write('drawable/splash.xml', `<?xml version="1.0" encoding="utf-8"?>
<layer-list xmlns:android="http://schemas.android.com/apk/res/android">
    <item><color android:color="@color/ic_launcher_background" /></item>
    <item android:drawable="@drawable/ic_launcher_foreground" android:gravity="center" android:width="216dp" android:height="216dp" />
</layer-list>
`)
console.log(`android-icons: ${paths.length} shapes, centre ${cx.toFixed(0)},${cy.toFixed(0)}, scale ${scale.toFixed(3)}`)
